def clear_existing_data() -> None:
    """
    Clears existing data to avoid duplication.
    """
    CatalogItem.objects.all().delete()
    Catalog.objects.all().delete()
    Material.objects.all().delete()
    Texture.objects.all().delete()


def create_textures() -> Dict[str, Texture]:
    """
    Creates texture records.
    Returns a dictionary mapping texture names to Texture objects.
    """
    texture_objects = {}
    for texture_data in TEXTURES:
        texture, created = Texture.objects.update_or_create(
            name=texture_data["name"],
            defaults={"image": texture_data["image"]},
        )
        texture_objects[texture_data["name"]] = texture
    return texture_objects


def create_materials(texture_objects: Dict[str, Texture]) -> Dict[str, Material]:
    """
    Creates material records and links them to textures.
    Returns a dictionary mapping material names to Material objects.
    """
    material_objects = {}
    for material_data in MATERIALS:
        texture_name = material_data["texture"]
        texture = texture_objects.get(texture_name)

        material, created = Material.objects.update_or_create(
            name=material_data["name"],
            defaults={"texture": texture},
        )
        material_objects[material_data["name"]] = material
    return material_objects


def create_catalogs() -> Dict[str, Catalog]:
    """
    Creates catalog records from the CATALOG list.
    Returns a dictionary mapping catalog names to Catalog objects.
    """
    catalog_objects = {}
    for catalog_data in CATALOG:
        if catalog_data["parent"] is None:
            catalog, created = Catalog.objects.update_or_create(
                name=catalog_data["name"],
                is_default=catalog_data["is_default"],
                defaults={
                    "image": catalog_data["image"],
                    "parent": None,
                    "data": catalog_data["data"],
                    "is_default": catalog_data["is_default"],
                },
            )
            catalog_objects[catalog_data["name"]] = catalog

    for catalog_data in CATALOG:
        if catalog_data["parent"] is not None:
            parent_name = catalog_data["parent"]
            parent_catalog = catalog_objects.get(parent_name)
            if not parent_catalog:
                continue

            catalog, created = Catalog.objects.update_or_create(
                name=catalog_data["name"],
                parent=parent_catalog,
                defaults={
                    "image": catalog_data["image"],
                    "parent": parent_catalog,
                    "data": catalog_data["data"],
                },
            )
            catalog_objects[catalog_data["name"]] = catalog
    return catalog_objects


def create_catalog_items(
    catalog_objects: Dict[str, Catalog], material_objects: Dict[str, Material]
) -> None:
    """
    Creates catalog items and links them to their respective catalogs and materials.
    """
    for catalog_item_data in CATALOG_ITEMS:
        catalog_name = catalog_item_data["catalog"]
        catalog = catalog_objects.get(catalog_name)
        if not catalog:
            continue
        material_name = (
            catalog_item_data["materials"][0]
            if catalog_item_data["materials"]
            else None
        )
        material = material_objects.get(material_name) if material_name else None

        catalog_item, created = CatalogItem.objects.update_or_create(
            name=catalog_item_data["name"],
            catalog=catalog,
            defaults={
                "material": material,
                "data": catalog_item_data["data"],
            },
        )


if __name__ == "__main__":
    textures = create_textures()
    materials = create_materials(textures)
    catalogs = create_catalogs()
    create_catalog_items(catalogs, materials)
